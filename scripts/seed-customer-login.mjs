/**
 * Idempotent customer-app login account.
 * Login rejects unknown phones, so this upserts the OTP test user first.
 *
 * Usage (from selorg-service):
 *   node scripts/seed-customer-login.mjs
 *
 * Phone / OTP match OTP_TEST_MOBILE and OTP_TEST_OTP (defaults 9698790921 / 8790).
 */
import mongoose from "mongoose";
import dotenv from "dotenv";
import path from "node:path";
import { fileURLToPath } from "node:url";
import dns from "node:dns";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
dotenv.config({ path: path.join(__dirname, "..", ".env") });

dns.setServers(["8.8.8.8", "1.1.1.1", "8.8.4.4"]);
dns.setDefaultResultOrder?.("ipv4first");

const MONGO_URI = process.env.MONGO_URI;
if (!MONGO_URI) throw new Error("MONGO_URI is not set in selorg-service/.env");

const PHONE = (process.env.OTP_TEST_MOBILE || "9698790921").replace(/\D/g, "").slice(-10);
const OTP = process.env.OTP_TEST_OTP || "8790";
const NAME = "Selorg Customer";

if (PHONE.length !== 10) throw new Error("OTP_TEST_MOBILE must be a 10-digit Indian mobile");

async function connectMongo(uri) {
  try {
    await mongoose.connect(uri, { serverSelectionTimeoutMS: 20000 });
    return;
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    if (!uri.startsWith("mongodb+srv://") || !/querySrv|ECONNREFUSED|ENOTFOUND/i.test(msg)) {
      throw err;
    }
    const { Resolver } = await import("node:dns/promises");
    const resolver = new Resolver();
    resolver.setServers(["8.8.8.8", "1.1.1.1"]);
    const m = uri.match(/^mongodb\+srv:\/\/([^@]+)@([^/?]+)(\/[^?]*)?(\?.*)?$/);
    if (!m) throw err;
    const [, auth, host, dbPath = "/", query = ""] = m;
    const records = await resolver.resolveSrv(`_mongodb._tcp.${host}`);
    const hosts = records.map((r) => `${r.name}:${r.port}`).join(",");
    const params = new URLSearchParams(query.startsWith("?") ? query.slice(1) : query);
    if (!params.has("ssl")) params.set("ssl", "true");
    if (!params.has("authSource")) params.set("authSource", "admin");
    if (!params.has("retryWrites")) params.set("retryWrites", "true");
    const direct = `mongodb://${auth}@${hosts}${dbPath || "/"}?${params.toString()}`;
    console.warn("seed: mongodb+srv SRV failed; retrying with direct hosts");
    await mongoose.connect(direct, { serverSelectionTimeoutMS: 20000 });
  }
}

await connectMongo(MONGO_URI);
const users = mongoose.connection.db.collection("customer_users");
const variants = [PHONE, `+91${PHONE}`, `91${PHONE}`];
const existing = await users.findOne({ phoneNumber: { $in: variants } });
const now = new Date();

if (existing) {
  await users.updateOne(
    { _id: existing._id },
    {
      $set: {
        phoneNumber: PHONE,
        phoneVerified: true,
        phoneVerifiedAt: existing.phoneVerifiedAt || now,
        status: "active",
        ...(existing.name ? {} : { name: NAME }),
        onboardingCompleted: existing.onboardingCompleted ?? true,
      },
    },
  );
  console.log("customer login already existed; ensured active");
  console.log(`  id    : ${String(existing._id)}`);
  console.log(`  name  : ${existing.name || NAME}`);
} else {
  const inserted = await users.insertOne({
    phoneNumber: PHONE,
    name: NAME,
    avatarUrl: "",
    phoneVerified: true,
    phoneVerifiedAt: now,
    onboardingCompleted: true,
    onboardingCompletedAt: now,
    acceptedTermsVersion: null,
    acceptedTermsAt: null,
    acceptedPrivacyVersion: null,
    acceptedPrivacyAt: null,
    passwordHash: null,
    isPasswordAutoGenerated: false,
    passwordLastChangedAt: null,
    passwordLastChangedBy: null,
    meta: { seeded: "customer-login" },
    lastLogin: null,
    loginCount: 0,
    status: "active",
    notificationPreferences: {
      push: true,
      inApp: true,
      sms: true,
      whatsapp: true,
      email: true,
      dnd: false,
      dndStartHour: 22,
      dndEndHour: 7,
    },
    createdAt: now,
    updatedAt: now,
  });
  console.log("customer login created");
  console.log(`  id    : ${String(inserted.insertedId)}`);
  console.log(`  name  : ${NAME}`);
}

console.log(`  phone : ${PHONE}`);
console.log(`  otp   : ${OTP} (fixed test OTP, non-production)`);
await mongoose.disconnect();
